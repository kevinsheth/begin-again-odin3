func zipFiles(t *testing.T, files map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	for name, body := range files {
		f, err := w.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := f.Write([]byte(body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// serveDSOAL serves an archive shaped like the DSOAL release.
func serveDSOAL(t *testing.T) {
	inner := zipFiles(t, map[string]string{
		"DSOAL/Win32/dsound.dll":                "dsound32",
		"DSOAL/Win32/dsoal-aldrv.dll":           "aldrv32",
		"DSOAL/Win64/dsound.dll":                "dsound64",
		"DSOAL/Documentation/DSOAL-License.txt": "license",
		"DSOAL/Documentation/DSOAL-ReadMe.txt":  "readme",
		"DSOAL+HRTF/Win32/dsound.dll":           "hrtf",
	})
	archive := zipFiles(t, map[string]string{"DSOAL_r695.zip": string(inner)})
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Write(archive)
	}))
	t.Cleanup(srv.Close)
	old := dsoalURL
	dsoalURL = srv.URL
	t.Cleanup(func() { dsoalURL = old })
}

const originalPrefs = "[Display]\r\n" + `sD3DDevice="AMD Radeon 780M Graphics"` + "\r\niSize W=1920\r\niSize H=1080\r\n"

// buildSource lays out Begin Again as Wabbajack leaves it on the build machine.
func buildSource(t *testing.T) (mo2, game string) {
	src := t.TempDir()
	mo2, game = filepath.Join(src, "mo2"), filepath.Join(src, "Fallout New Vegas")
	writeTestFile(t, filepath.Join(mo2, "ModOrganizer.ini"), crlf(
		"[General]",
		`gamePath=@ByteArray(D:\\SteamLibrary\\steamapps\\common\\Fallout New Vegas)`,
		"selected_profile=@ByteArray(Begin Again)",
		"[customExecutables]",
		"1\\binary=D:/SteamLibrary/steamapps/common/Fallout New Vegas/FalloutNV.exe",
		"1\\title=Begin Again",
		"1\\workingDirectory=D:/SteamLibrary/steamapps/common/fallout new vegas",
		"2\\binary=C:/Games/Begin Again/tools/FNVEdit.exe",
		"[Settings]",
		"base_directory=C:/Games/Begin Again",
		"download_directory=C:/Games/Begin Again/downloads",
		"[Plugins]",
		`RootBuilder\exclusions="Data"`,
	))
	profile := filepath.Join(mo2, "profiles", "Begin Again")
	writeTestFile(t, filepath.Join(profile, "modlist.txt"), crlf("# This file was automatically generated by Mod Organizer.", "+Begin Again Configs", "+lStewieAl's Tweaks and Engine Fixes"))
	writeTestFile(t, filepath.Join(profile, "settings.ini"), crlf("[General]", "LocalSaves=false"))
	writeTestFile(t, filepath.Join(profile, "falloutprefs.ini"), originalPrefs)
	writeTestFile(t, filepath.Join(profile, "falloutcustom.ini"), crlf("[Display]", "iSize W=1920"))
	writeTestFile(t, filepath.Join(mo2, "mods", "Begin Again Configs", "NVSE", "Plugins", "nvse_stewie_tweaks.ini"),
		crlf("[Tweaks]", "bToggleControllerIfAttackPressed=1", "sFrom=configs"))
	writeTestFile(t, filepath.Join(mo2, "mods", "lStewieAl's Tweaks and Engine Fixes", "NVSE", "plugins", "nvse_stewie_tweaks.dll"), "stewie")
	writeTestFile(t, filepath.Join(mo2, "downloads", "big.7z"), "archive")
	writeTestFile(t, filepath.Join(game, "FalloutNV.exe"), "exe")
	writeTestFile(t, filepath.Join(game, "dxvk.conf"), "d3d9.maxFrameRate = 60\n")
	return mo2, game
}

func TestRun(t *testing.T) {
	serveDSOAL(t)
	mo2, game := buildSource(t)
	home := t.TempDir()
	dir := filepath.Join(home, "BeginAgain")
	manager := filepath.Join(dir, "manager")
	profile := filepath.Join(manager, "profiles", "Begin Again")

	steam := filepath.Join(home, "Steam")
	shortcuts := filepath.Join(steam, "userdata", "12345", "config", "shortcuts.vdf")
	writeTestFile(t, shortcuts, string(shortcutsFixture()))
	writeTestFile(t, filepath.Join(steam, "config", "config.vdf"), configFixture)

	configPath := filepath.Join(home, "begin-again-odin3.ini")
	if err := run(configPath, steam); err != nil {
		t.Fatal(err)
	}
	if got := readTestFile(t, configPath); got != configTemplate {
		t.Fatal("first run didn't write the template")
	}
	config := strings.Replace(configTemplate, "mo2 =\ngame =", "mo2 = "+mo2+"\ngame = "+game, 1)
	config = strings.Replace(config, "dir = ~/Games/BeginAgain", "dir = "+dir, 1)
	writeTestFile(t, configPath, config+"\n[Display]\niSize W=1600\niSize H=900\n")

	if err := run(configPath, steam); err != nil {
		t.Fatal(err)
	}

	t.Run("copy", func(t *testing.T) {
		if _, err := os.Stat(filepath.Join(manager, "downloads")); err == nil {
			t.Error("downloads copied")
		}
		if _, err := os.Stat(filepath.Join(dir, "game", "FalloutNV.exe")); err != nil {
			t.Error("game not copied")
		}
	})

	t.Run("paths", func(t *testing.T) {
		ini := readTestFile(t, filepath.Join(manager, "ModOrganizer.ini"))
		gameWin := windowsPath(filepath.Join(dir, "game"))
		for _, want := range []string{
			"gamePath=@ByteArray(" + strings.ReplaceAll(gameWin, `\`, `\\`) + ")\r\n",
			"1\\binary=" + strings.ReplaceAll(gameWin, `\`, "/") + "/FalloutNV.exe\r\n",
			"1\\workingDirectory=" + strings.ReplaceAll(gameWin, `\`, "/") + "\r\n",
			"2\\binary=" + strings.ReplaceAll(windowsPath(manager), `\`, "/") + "/tools/FNVEdit.exe\r\n",
			"selected_profile=@ByteArray(Begin Again)\r\n",
			"RootBuilder\\exclusions=" + rootBuilderExclusions + "\r\n",
		} {
			if !strings.Contains(ini, want) {
				t.Errorf("ModOrganizer.ini lacks %q", want)
			}
		}
	})

	t.Run("stewie", func(t *testing.T) {
		mod := filepath.Join(manager, "mods", "lStewieAl's Tweaks and Engine Fixes")
		if readTestFile(t, filepath.Join(mod, "Root", "Data", "NVSE", "Plugins", "nvse_stewie_tweaks.dll")) != "stewie" {
			t.Error("DLL not copied for Root Builder")
		}
		if _, err := os.Stat(filepath.Join(mod, "NVSE", "plugins", "nvse_stewie_tweaks.dll.mohidden")); err != nil {
			t.Error("original DLL not hidden")
		}
	})

	t.Run("dsoal", func(t *testing.T) {
		root := filepath.Join(manager, "mods", dsoalMod, "Root")
		if readTestFile(t, filepath.Join(root, "dsound.dll")) != "dsound32" {
			t.Error("Win32 dsound.dll not installed")
		}
		if _, err := os.Stat(filepath.Join(root, "DSOAL-licenses", "DSOAL-License.txt")); err != nil {
			t.Error("license not kept")
		}
	})

	t.Run("settings", func(t *testing.T) {
		prefs := readTestFile(t, filepath.Join(profile, "falloutprefs.ini"))
		for _, want := range []string{"iSize W=1600\r\n", "iSize H=900\r\n", "sD3DDevice=" + odinDevice + "\r\n"} {
			if !strings.Contains(prefs, want) {
				t.Errorf("falloutprefs.ini lacks %q", want)
			}
		}
		if readTestFile(t, filepath.Join(profile, "falloutprefs.ini"+backupSuffix)) != originalPrefs {
			t.Error("original INI not kept")
		}
		modlist := readTestFile(t, filepath.Join(profile, "modlist.txt"))
		if !strings.HasPrefix(modlist, crlf("# This file was automatically generated by Mod Organizer.", "+"+touchFixMod, "+"+dsoalMod)) {
			t.Errorf("modlist:\n%s", modlist)
		}
		touch := readTestFile(t, filepath.Join(manager, "mods", touchFixMod, "NVSE", "Plugins", "nvse_stewie_tweaks.ini"))
		if !strings.Contains(touch, "bToggleControllerIfAttackPressed=0\r\n") || !strings.Contains(touch, "sFrom=configs") {
			t.Errorf("touch fix INI:\n%s", touch)
		}
	})

	t.Run("steam", func(t *testing.T) {
		doc, err := parseVDF([]byte(readTestFile(t, shortcuts)))
		if err != nil {
			t.Fatal(err)
		}
		list := doc.child("shortcuts").nodes
		if len(list) != 2 || list[0].child("big").num != 1<<40 {
			t.Fatal("existing shortcut lost or changed")
		}
		entry := list[1]
		if entry.child("Exe").str != `"`+filepath.Join(manager, "ModOrganizer.exe")+`"` {
			t.Errorf("Exe is %s", entry.child("Exe").str)
		}
		if !strings.HasPrefix(entry.child("LaunchOptions").str, `WINEDLLOVERRIDES="dsound=n,b" DXVK_CONFIG_FILE=`) {
			t.Errorf("LaunchOptions is %s", entry.child("LaunchOptions").str)
		}
		id := strconv.FormatUint(entry.child("appid").num, 10)
		if !strings.Contains(readTestFile(t, filepath.Join(steam, "config", "config.vdf")), "\""+id+"\"\n\t\t\t\t\t{\n\t\t\t\t\t\t\"name\"\t\t\"proton-experimental-arm64\"") {
			t.Error("compatibility tool not set")
		}
	})

	// Removing a setting from the config restores Begin Again's value, and
	// running again doesn't duplicate anything.
	writeTestFile(t, configPath, config)
	if err := run(configPath, steam); err != nil {
		t.Fatal(err)
	}
	prefs := readTestFile(t, filepath.Join(profile, "falloutprefs.ini"))
	if !strings.Contains(prefs, "iSize W=1920\r\n") {
		t.Errorf("removed setting not restored:\n%s", prefs)
	}
	doc, err := parseVDF([]byte(readTestFile(t, shortcuts)))
	if err != nil {
		t.Fatal(err)
	}
	if n := len(doc.child("shortcuts").nodes); n != 2 {
		t.Errorf("%d shortcuts after rerun", n)
	}
	if n := strings.Count(readTestFile(t, filepath.Join(profile, "modlist.txt")), dsoalMod); n != 1 {
		t.Errorf("DSOAL listed %d times", n)
	}
}
