#!/usr/bin/env bash
# Runs odin-preset against a synthetic Mod Organizer folder. Needs Linux
# (GNU sed, find and bash 4+), like the script itself.
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mo2="$work/mo2"
failures=0

check() {
    if ! grep -qxF -- "$2" "$1"; then
        echo "FAIL: $(basename "$1") lacks '$2'"
        failures=$((failures + 1))
    fi
}

refute() {
    if grep -qxF -- "$2" "$1"; then
        echo "FAIL: $(basename "$1") still has '$2'"
        failures=$((failures + 1))
    fi
}

crlf() { printf '%s\r\n' "$@"; }

mkdir -p "$mo2/profiles/Base" "$mo2/mods/Configs/NVSE/Plugins" "$mo2/mods/Lower/NVSE/Plugins"
crlf '[General]' 'selected_profile=@ByteArray(Base)' > "$mo2/ModOrganizer.ini"
crlf '[General]' 'LocalSaves=false' > "$mo2/profiles/Base/settings.ini"
crlf '# This file was automatically generated by Mod Organizer.' '+Configs' '+Lower' > "$mo2/profiles/Base/modlist.txt"
crlf '[Display]' 'sD3DDevice="PC GPU"' 'iSize W=1920' 'iSize H=1080' '[Grass]' 'b30GrassVS=1' 'b30GrassVS=1' > "$mo2/profiles/Base/falloutcustom.ini"
crlf '[Display]' 'iSize W = 1920' 'iSize H = 1080' '[General]' 'sLanguage=ENGLISH' > "$mo2/profiles/Base/falloutprefs.ini"
crlf '[Tweaks]' 'bToggleControllerIfAttackPressed=1' 'sSource=configs' > "$mo2/mods/Configs/NVSE/Plugins/nvse_stewie_tweaks.ini"
crlf '[Exterior]' 'bEnabled = 1' '[Interior]' 'bEnabled = 1' > "$mo2/mods/Configs/NVSE/Plugins/VanillaPlusAO.ini"
crlf '[Tweaks]' 'bToggleControllerIfAttackPressed=5' > "$mo2/mods/Lower/NVSE/Plugins/nvse_stewie_tweaks.ini"

"$repo/scripts/odin-preset" apply balanced --mo2 "$mo2" > /dev/null
profile="$mo2/profiles/Odin Balanced"

check "$mo2/ModOrganizer.ini" $'selected_profile=@ByteArray(Odin Balanced)\r'
check "$profile/falloutcustom.ini" $'iSize W=1600\r'
check "$profile/falloutcustom.ini" $'sD3DDevice="AMD Radeon RX 6700 XT"\r'
refute "$profile/falloutcustom.ini" $'b30GrassVS=1\r'
check "$profile/falloutcustom.ini" $'[LOD]\r'
check "$profile/falloutprefs.ini" $'iSize W = 1600\r'
check "$profile/falloutprefs.ini" $'sLanguage=ENGLISH\r'
check "$profile/settings.ini" $'LocalSettings=true\r'
check "$mo2/profiles/Base/falloutcustom.ini" $'iSize W=1920\r'
if grep -qv $'\r$' "$profile/falloutcustom.ini"; then
    echo "FAIL: falloutcustom.ini lost CRLF line endings"
    failures=$((failures + 1))
fi
[[ $(grep -c '^b30GrassVS=0' "$profile/falloutcustom.ini") -eq 2 ]] || { echo "FAIL: duplicate keys not all updated"; failures=$((failures + 1)); }

check "$mo2/mods/Odin Touchscreen Fix/NVSE/Plugins/nvse_stewie_tweaks.ini" $'bToggleControllerIfAttackPressed=0\r'
check "$mo2/mods/Odin Touchscreen Fix/NVSE/Plugins/nvse_stewie_tweaks.ini" $'sSource=configs\r'
check "$mo2/mods/Odin Ambient Occlusion Off/NVSE/Plugins/VanillaPlusAO.ini" $'bEnabled = 0\r'
[[ $(sed -n 2,3p "$profile/modlist.txt" | tr -d '\r' | tr '\n' ,) == "+Odin Ambient Occlusion Off,+Odin Touchscreen Fix," ]] \
    || { echo "FAIL: tweak mods not at top of modlist"; failures=$((failures + 1)); }

"$repo/scripts/odin-preset" apply quality --mo2 "$mo2" --from "Odin Balanced" --keep-selection > /dev/null
check "$mo2/ModOrganizer.ini" $'selected_profile=@ByteArray(Odin Balanced)\r'
check "$mo2/profiles/Odin Quality/modlist.txt" $'-Odin Ambient Occlusion Off\r'
[[ $(grep -c 'Odin Touchscreen Fix' "$mo2/profiles/Odin Quality/modlist.txt") -eq 1 ]] \
    || { echo "FAIL: touchscreen mod duplicated"; failures=$((failures + 1)); }

if "$repo/scripts/odin-preset" apply balanced --mo2 "$mo2" --from Base 2> /dev/null; then
    echo "FAIL: overwrote an existing profile"
    failures=$((failures + 1))
fi

if [[ $failures -eq 0 ]]; then echo "All checks passed."; else exit 1; fi
